// Derive the animated wordmark and its compact icon from the original artwork.
// Never redraw the letterforms or replace public/radovar-logo.svg.
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const original = await readFile(path.join(root, 'public/radovar-logo.svg'), 'utf8');
const paths = [...original.matchAll(/<path\b[^>]*\bd="([^"]+)"/g)].map(match => match[1]);
if (paths.length !== 2) throw new Error('Review the original artwork before regenerating its derivatives.');
const [arc, letters] = paths;
const starts = ['M1052.46', 'M1021.95', 'M317.922', 'M0.500141', 'M347.765', 'M679.024', 'M564.159'];
const names = ['r2', 'a2', 'a', 'r', 'd', 'v', 'o'];
const glyphs = Object.fromEntries(starts.map((start, index) => {
  const begin = letters.indexOf(start);
  const end = index + 1 < starts.length ? letters.indexOf(starts[index + 1]) : letters.length;
  if (begin < 0 || end <= begin) throw new Error(`Original glyph boundary changed: ${start}`);
  return [names[index], letters.slice(begin, end)];
}));

// The R matrix is shared with the favicon; the arc matrix supports older browsers.
const compact = {
  initial: 'matrix(1.5, 0, 0, 1.5, 28, -8)',
  arc: 'matrix(0.215192, -0.045741, 0.103956, 0.489074, -14.495, 157.061)',
};
// Optical finishing stroke: level tapered tips, centered below the R with equal
// clearance on both sides. The expanded original arc is never redrawn.
const tokens = arc.match(/[MLHVZ]|-?(?:\d*\.)?\d+/g);
const vertices = [];
let cursor = [0, 0];
for (let index = 0; index < tokens.length;) {
  const command = tokens[index++];
  if (command === 'Z') break;
  if (command === 'M' || command === 'L') cursor = [Number(tokens[index++]), Number(tokens[index++])];
  else if (command === 'H') cursor = [Number(tokens[index++]), cursor[1]];
  else if (command === 'V') cursor = [cursor[0], Number(tokens[index++])];
  else throw new Error('Review newly introduced original arc commands before regenerating.');
  vertices.push(cursor);
}
const distance = (a, b) => Math.hypot(b[0] - a[0], b[1] - a[1]);
function measure(points) {
  const lengths = [0];
  for (let i = 1; i < points.length; i++) lengths.push(lengths.at(-1) + distance(points[i - 1], points[i]));
  return lengths;
}
function cubic(a, b, c, d, t) {
  return [0, 1].map(axis => (1 - t) ** 3 * a[axis] + 3 * (1 - t) ** 2 * t * b[axis] + 3 * (1 - t) * t ** 2 * c[axis] + t ** 3 * d[axis]);
}
const top = Array.from({ length: 513 }, (_, i) => cubic([25, 213.8889], [82, 250], [170.806, 250], [227.806, 213.8889], i / 512));
const bottom = [[227.806, 213.8889], ...Array.from({ length: 513 }, (_, i) => cubic([227.806, 213.8889], [170.806, 264], [82, 264], [25, 213.8889], i / 512))];
function along(points, fraction) {
  const lengths = measure(points);
  const at = fraction * lengths.at(-1);
  const end = lengths.findIndex(length => length >= at);
  if (end <= 0) return points[0];
  const part = (at - lengths[end - 1]) / (lengths[end] - lengths[end - 1]);
  return [0, 1].map(axis => points[end - 1][axis] + (points[end][axis] - points[end - 1][axis]) * part);
}
const tip = vertices.reduce((best, point, index) => point[0] > vertices[best][0] ? index : best, 0);
const upperLengths = measure(vertices.slice(0, tip + 1));
const lowerLengths = measure([...vertices.slice(tip), vertices[0]]);
const compactVertices = vertices.map((point, index) => index <= tip
  ? along(top, upperLengths[index] / upperLengths.at(-1))
  : along(bottom, lowerLengths[index - tip] / lowerLengths.at(-1)));
const polygon = points => points.map((point, index) => `${index ? 'L' : 'M'}${point.map(value => Number(value.toFixed(4))).join(' ')}`).join(' ') + ' Z';
// Matching command sequences make a real, reversible browser-native path morph.
const arcMorph = { expanded: polygon(vertices), compact: polygon(compactVertices) };
const data = { ...glyphs, arc };
await writeFile(path.join(root, 'app/_components/radovar-brand-paths.ts'),
  '// Generated by scripts/build-brand-assets.mjs from the unchanged original wordmark.\n' +
  `export const radovarBrandPaths = ${JSON.stringify(data, null, 2)} as const;\n` +
  `export const radovarCompactTransforms = ${JSON.stringify(compact, null, 2)} as const;\n` +
  `export const radovarArcMorph = ${JSON.stringify(arcMorph, null, 2)} as const;\n`);

// A warm white tile with breathing room around the near-black original symbol, legible at tab size.
const icon = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64" width="64" height="64"><title>Radovar</title><rect width="64" height="64" rx="14" fill="#fffdf7"/><g fill="#141413" transform="translate(9.79 10.12) scale(.176)"><path d="${arcMorph.compact}"/><path fill-rule="evenodd" clip-rule="evenodd" d="${glyphs.r}" transform="${compact.initial}"/></g></svg>\n`;
await writeFile(path.join(root, 'public/radovar-icon.svg'), icon);
await writeFile(path.join(root, 'app/icon.svg'), icon);
await sharp(Buffer.from(icon), { density: 288 }).resize(180, 180).png().toFile(path.join(root, 'app/apple-icon.png'));

const sizes = [16, 32, 48];
const pngs = await Promise.all(sizes.map(size => sharp(Buffer.from(icon), { density: 288 }).resize(size, size).png().toBuffer()));
const icoHeader = Buffer.alloc(6 + sizes.length * 16);
icoHeader.writeUInt16LE(1, 2);
icoHeader.writeUInt16LE(sizes.length, 4);
let offset = icoHeader.length;
pngs.forEach((png, index) => {
  const entry = 6 + index * 16;
  icoHeader[entry] = sizes[index];
  icoHeader[entry + 1] = sizes[index];
  icoHeader.writeUInt16LE(1, entry + 4);
  icoHeader.writeUInt16LE(32, entry + 6);
  icoHeader.writeUInt32LE(png.length, entry + 8);
  icoHeader.writeUInt32LE(offset, entry + 12);
  offset += png.length;
});
await writeFile(path.join(root, 'public/favicon.ico'), Buffer.concat([icoHeader, ...pngs]));
console.log('Generated original Radovar letterforms, R + arc icon, Apple icon and 16/32/48 ICO.');
